export const SUPPORTED_LANGUAGES = definitions.map(([code, englishName, nativeName, dir, script]) => ({
  code,
  englishName,
  nativeName,
  dir,
  script,
  speechLang: speechOverrides[code] || code,
}));

export const DEFAULT_LANGUAGE = SUPPORTED_LANGUAGES[0];

export function getLanguage(code) {
  const normalized = String(code || '').toLowerCase();
  return SUPPORTED_LANGUAGES.find((item) => item.code.toLowerCase() === normalized)
    || SUPPORTED_LANGUAGES.find((item) => item.code.toLowerCase().split('-')[0] === normalized.split('-')[0])
    || DEFAULT_LANGUAGE;
}

export function isRtlLanguage(code) {
  return rtlCodes.has(String(code || '').toLowerCase().split('-')[0]);
}
