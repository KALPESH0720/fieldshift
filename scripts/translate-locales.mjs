  const merged = mergeObjects(structuredClone(source), existing);
  Object.entries(overrides[language.code] || {}).forEach(([key, value]) => setPath(merged, key, value));
  const translated = await translateWithApi(merged, language);
  const missing = flatten(source);
  Object.keys(flatten(translated)).forEach((key) => delete missing[key]);
  await mkdir(dirname(targetPath), { recursive: true });
