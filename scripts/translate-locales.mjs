function setPath(target, path, value) {
  const parts = path.split('.');
  let cursor = target;
  parts.slice(0, -1).forEach((part) => { cursor = cursor[part] ||= {}; });
  cursor[parts.at(-1)] = value;
}

function mergeObjects(base, extra) {
  Object.entries(extra).forEach(([key, value]) => {
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      base[key] = mergeObjects(base[key] && typeof base[key] === 'object' ? base[key] : {}, value);
    } else {
      base[key] = value;
    }
  });
  return base;
}

function flatten(value, prefix = '', result = {}) {
  Object.entries(value).forEach(([key, child]) => {
    const path = prefix ? `${prefix}.${key}` : key;
    if (child && typeof child === 'object' && !Array.isArray(child)) flatten(child, path, result);
    else result[path] = child;
  });
  return result;
}

async function translateWithApi(target, language) {
  if (!apiUrl || !apiKey) return target;
  const response = await fetch(apiUrl, {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: `Bearer ${apiKey}` },
    body: JSON.stringify({ source: 'en', target: language.code, values: flatten(target) }),
  });
  if (!response.ok) throw new Error(`Translation API failed for ${language.code}: ${response.status}`);
  return (await response.json()).translation || target;
}

